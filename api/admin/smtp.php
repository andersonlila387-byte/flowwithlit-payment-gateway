<?php
declare(strict_types=1);

require_once __DIR__ . '/../_admin.php';
require_once __DIR__ . '/../../services/EmailService.php';

header('Cache-Control: no-store');
$input = adminMethod(['GET', 'POST']);
$pdo = Database::getInstance();
[$session, $role] = requireAdmin($pdo, $input);
requireAdminRole($role, ['super_admin'], 'manage SMTP settings');

const FLOW_SMTP_CONFIG = __DIR__ . '/../../config/smtp.local.php';

function smtpStoredConfig(): array {
    $stored = is_file(FLOW_SMTP_CONFIG) ? require FLOW_SMTP_CONFIG : [];
    return is_array($stored) ? $stored : [];
}

function smtpInputConfig(array $input, array $stored): array {
    $smtp = is_array($input['smtp'] ?? null) ? $input['smtp'] : [];
    $password = trim((string)($smtp['password'] ?? ''));
    $config = [
        'host' => trim((string)($smtp['host'] ?? '')),
        'port' => (int)($smtp['port'] ?? 587),
        'username' => trim((string)($smtp['username'] ?? '')),
        'password' => $password !== '' ? $password : (string)($stored['password'] ?? ''),
        'encryption' => (string)($smtp['encryption'] ?? 'tls'),
        'from_address' => strtolower(trim((string)($smtp['from_address'] ?? ''))),
        'from_name' => trim((string)($smtp['from_name'] ?? 'Flowwithlit')),
    ];
    if ($config['host'] === '' || strlen($config['host']) > 255 || $config['port'] < 1 || $config['port'] > 65535 || $config['username'] === '' || $config['password'] === '' || !filter_var($config['from_address'], FILTER_VALIDATE_EMAIL) || $config['from_name'] === '' || strlen($config['from_name']) > 150 || !in_array($config['encryption'], ['tls', 'ssl'], true)) {
        jsonResponse(['success' => false, 'error' => 'Enter a valid host, port, username, password, sender email, and encryption type.'], 422);
    }
    return $config;
}

function smtpPublicConfig(array $smtp): array {
    return ['configured' => !empty($smtp['host']) && !empty($smtp['username']) && !empty($smtp['password']), 'host' => (string)($smtp['host'] ?? ''), 'port' => (int)($smtp['port'] ?? 587), 'username' => (string)($smtp['username'] ?? ''), 'encryption' => (string)($smtp['encryption'] ?? 'tls'), 'from_address' => (string)($smtp['from_address'] ?? ''), 'from_name' => (string)($smtp['from_name'] ?? 'Flowwithlit')];
}

if ($_SERVER['REQUEST_METHOD'] === 'GET') jsonResponse(['success' => true, 'smtp' => smtpPublicConfig(smtpStoredConfig()), 'phpmailer_ready' => is_file(__DIR__ . '/../../vendor/autoload.php')]);

$action = (string)($input['action'] ?? '');
$stored = smtpStoredConfig();
$smtp = smtpInputConfig($input, $stored);

if ($action === 'save') {
    $directory = dirname(FLOW_SMTP_CONFIG);
    if (!is_dir($directory) && !mkdir($directory, 0750, true)) jsonResponse(['success' => false, 'error' => 'SMTP settings directory could not be created.'], 500);
    $temporary = FLOW_SMTP_CONFIG . '.tmp';
    $contents = "<?php\n// Generated by the protected Flowwithlit admin API. Do not commit this file.\nreturn " . var_export($smtp, true) . ";\n";
    if (file_put_contents($temporary, $contents, LOCK_EX) === false || !rename($temporary, FLOW_SMTP_CONFIG)) { @unlink($temporary); jsonResponse(['success' => false, 'error' => 'SMTP settings could not be saved. Check server write permissions.'], 500); }
    @chmod(FLOW_SMTP_CONFIG, 0600);
    adminAudit($pdo, (int)$session['admin']['id'], 'admin.smtp_settings_saved', 'smtp', 'configuration');
    jsonResponse(['success' => true, 'message' => 'SMTP settings saved securely.', 'smtp' => smtpPublicConfig($smtp)]);
}

if ($action === 'test') {
    $recipient = strtolower(trim((string)($input['recipient'] ?? '')));
    if (!filter_var($recipient, FILTER_VALIDATE_EMAIL)) jsonResponse(['success' => false, 'error' => 'Enter a valid test recipient email.'], 422);
    try {
        EmailService::sendTest($recipient, $smtp);
        adminAudit($pdo, (int)$session['admin']['id'], 'admin.smtp_test_sent', 'smtp', 'configuration', ['recipient' => $recipient]);
        jsonResponse(['success' => true, 'message' => 'Test email sent to '.$recipient.'. Check its inbox and spam folder.']);
    } catch (Throwable $error) {
        error_log('SMTP test failed: '.$error->getMessage());
        jsonResponse(['success' => false, 'error' => 'SMTP test failed: '.$error->getMessage()], 422);
    }
}

jsonResponse(['success' => false, 'error' => 'Unknown SMTP action.'], 422);
